DROP TABLE IF EXISTS teaching_assignments CASCADE;
DROP TABLE IF EXISTS teachers CASCADE;
DROP TABLE IF EXISTS disciplines CASCADE;
DROP TABLE IF EXISTS departments CASCADE;

CREATE TABLE departments (
    department_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(150) NOT NULL
);

CREATE TABLE teachers (
    teacher_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    address       VARCHAR(200),
    position      VARCHAR(50) NOT NULL,
    email         VARCHAR(100) NOT NULL UNIQUE,
    phone         VARCHAR(20) NOT NULL,
    department_id INT NOT NULL REFERENCES departments (department_id)
);

CREATE TABLE disciplines (
    discipline_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discipline_name VARCHAR(150) NOT NULL,
    hours_count     INT NOT NULL,
    control_type    VARCHAR(30) NOT NULL
);

CREATE TABLE teaching_assignments (
    assignment_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id       INT NOT NULL REFERENCES teachers (teacher_id) ON DELETE CASCADE,
    discipline_id    INT NOT NULL REFERENCES disciplines (discipline_id) ON DELETE CASCADE,
    classroom_number VARCHAR(20) NOT NULL,
    UNIQUE (teacher_id, discipline_id)
);

